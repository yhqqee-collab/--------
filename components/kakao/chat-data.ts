export type ChatItem =
  | { type: 'date'; label: string }
  | { type: 'break' }
  | { type: 'msg'; from: 'me' | 'them'; text: string; time: string; unread?: boolean | number; sender?: string; image?: boolean | string }

export type Chat = {
  id: string
  name: string
  /** 단톡방 인원 수 (지정하면 헤더와 목록에 표시) */
  members?: number
  /** 단톡방 대화상대 목록 (지정하면 ☰ 메뉴에서 볼 수 있음). '나'는 본인으로 표시 */
  roster?: string[]
  /** 단톡방 상단 고정 공지 (접힌 상태에서는 title, 펼치면 lines 전체) */
  notice?: { author: string; title: string; lines: string[] }
  avatar?: string
  preview: string
  time: string
  unread?: number
  pinned?: boolean
  self?: boolean
  items: ChatItem[]
}

/** 대화가 불가능한 배경용 채팅방 (목록에만 표시) */
export type BackgroundChat = {
  name: string
  preview: string
  time: string
  color: string
  avatar?: string
  members?: number
  unread?: number
  muted?: boolean
}

const day = (label: string): ChatItem => ({ type: 'date', label })

function block(time: string, lines: [from: 'me' | 'them', text: string][]): ChatItem[] {
  return lines.map(([from, text]) => ({ type: 'msg', from, text, time }))
}

function group(sender: string, time: string, lines: (string | { image: true | string })[]): ChatItem[] {
  return lines.map((line) =>
    typeof line === 'string'
      ? { type: 'msg', from: 'them', sender, text: line, time }
      : { type: 'msg', from: 'them', sender, text: '사진', image: line.image, time },
  )
}


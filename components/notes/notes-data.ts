export function splitNote(note: Note) {
  const [title, ...rest] = note.body.split('\n')
  return { title, content: rest.join('\n') }
}

/** 목록 미리보기용: 마크업 기호를 제거한 평문 */
export function previewText(content: string) {
  return content
    .split('\n')
    .map((l) => l.replace(/^\s*-\s(\[[ x]\]\s)?/, '').replace(/\*\*/g, ''))
    .filter((l) => l && l !== '---')
    .join(' ')
}
